class PromptCapsuleTag {
  final String en;
  final String zh;

  const PromptCapsuleTag({required this.en, required this.zh});

  String get promptText => en.replaceAll('_', ' ').trim();

  bool matches(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return true;
    return en.toLowerCase().contains(q) || zh.toLowerCase().contains(q);
  }
}

