List<PromptCapsuleCategory> filterPromptCapsuleCategories(
  String query, {
  List<PromptCapsuleCategory> source = promptCapsuleCategories,
}) {
  final trimmed = query.trim();
  if (trimmed.isEmpty) return source;
  return source
      .map((category) {
        final subgroups = category.subgroups
            .map((subgroup) => PromptCapsuleSubgroup(
                  name: subgroup.name,
                  tags: subgroup.tags
                      .where((tag) => tag.matches(trimmed))
                      .toList(growable: false),
                ))
            .where((subgroup) => subgroup.tags.isNotEmpty)
            .toList(growable: false);
        return PromptCapsuleCategory(name: category.name, subgroups: subgroups);
      })
      .where((category) => category.subgroups.isNotEmpty)
      .toList(growable: false);
}
